#!/usr/bin/env bash
# Regenerates app/proguard-device-tests.pro, the keep rules for what the device
# tests (app/src/androidTest) and the test libraries they run with call in the app
# and the libraries it ships. On the minified build R8 is otherwise free to remove
# or inline any of it the app itself does not need, and the tests then fail on a
# missing class or method. R8's TraceReferences reads the compiled tests and lists
# exactly those references. Run it after changing the device tests or the
# dependencies; a stale file fails the minified run in "Fork - Android device tests".
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -z "${JAVA_HOME:-}" && -x /usr/libexec/java_home ]]; then
    JAVA_HOME="$(/usr/libexec/java_home -v 21)"
    export JAVA_HOME
fi
java="${JAVA_HOME:+$JAVA_HOME/bin/}java"
jar="${JAVA_HOME:+$JAVA_HOME/bin/}jar"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Asks Gradle where everything is: the compiled app and tests, each one's runtime
# classpath, android.jar, and the R8 that the Android Gradle plugin bundles.
cat >"$work/paths.gradle" <<'EOF'
gradle.projectsEvaluated {
    def p = gradle.rootProject.project(':app')
    def jars = { String name ->
        p.configurations.getByName(name).incoming.artifactView {
            attributes { attribute(Attribute.of('artifactType', String), 'android-classes-jar') }
        }.files
    }
    def app = jars('debugRuntimeClasspath')
    def test = jars('debugAndroidTestRuntimeClasspath')
    def out = new File(System.getProperty('frigate.pathsOut'))
    def classes = { String task -> p.tasks.named(task).get().destinationDirectory.get().asFile }
    def boot = p.extensions.getByName('androidComponents').sdkComponents.bootClasspath
    def r8 = p.plugins.getPlugin('com.android.application').getClass().classLoader
        .loadClass('com.android.tools.r8.tracereferences.TraceReferences')
        .protectionDomain.codeSource.location.toURI().path
    p.tasks.register('deviceTestPaths') {
        dependsOn 'compileDebugKotlin', 'compileDebugAndroidTestKotlin'
        inputs.files(app)
        inputs.files(test)
        doLast {
            new File(out, 'app-classes').text = classes('compileDebugKotlin')
            new File(out, 'test-classes').text = classes('compileDebugAndroidTestKotlin')
            new File(out, 'app-jars').text = app.files.join('\n') + '\n'
            new File(out, 'test-jars').text = test.files.join('\n') + '\n'
            new File(out, 'boot').text = boot.get()*.asFile.join('\n') + '\n'
            new File(out, 'r8').text = r8
        }
    }
}
EOF
./gradlew -q --no-configuration-cache -I "$work/paths.gradle" -Dfrigate.pathsOut="$work" :app:deviceTestPaths

"$jar" cf "$work/app.jar" -C "$(cat "$work/app-classes")" .
"$jar" cf "$work/test.jar" -C "$(cat "$work/test-classes")" .

# The tests and the test-only libraries are the source of the references; the
# app and every library it ships are the target the rules keep. They keep names
# too: R8 9.5 writes the new name of an empty method, such as
# DebugProbesKt.probeCoroutineSuspended, in a form the test APK's build does not
# read back from the mapping, so a renamed one is missing on the device.
args=(--keep-rules --output "$work/traced.pro" --source "$work/test.jar" --target "$work/app.jar")
while read -r lib; do args+=(--lib "$lib"); done <"$work/boot"
while read -r target; do args+=(--target "$target"); done < <(sort "$work/app-jars")
while read -r source; do args+=(--source "$source"); done < <(comm -13 <(sort "$work/app-jars") <(sort "$work/test-jars"))
# The test libraries refer to classes nothing ships, such as JUnit 3's and
# EasyMock's; those are the test APK's concern (proguard-test-apk.pro), not the app's.
"$java" -cp "$(cat "$work/r8")" com.android.tools.r8.tracereferences.TraceReferences \
    --map-diagnostics error info "${args[@]}" >"$work/trace.log" 2>&1 || {
    cat "$work/trace.log" >&2
    exit 1
}

{
    echo "# Generated by scripts/device-test-keep-rules.sh, which says when to rerun it."
    echo "# Do not edit by hand. The minified build type only: what the device tests"
    echo "# and their test libraries call in the app and the libraries it ships, kept"
    echo "# under its own name. Everything else is shrunk as for release."
    cat "$work/traced.pro"
} >app/proguard-device-tests.pro
echo "Wrote app/proguard-device-tests.pro ($(grep -c '^-keep' app/proguard-device-tests.pro) rules)"
